function resolveIconName(name) {
  return FLUENT_ICON_DEFS[name] ? name : (LUCIDE_ICON_ALIASES[name] || name);
}

function buildFluentSvg(definition, size = 20, filled = false) {
  const paths = definition || [];
  const markup = paths.join('');
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${markup}</svg>`;
}

export function fluentIcon(name, options = {}) {
  const { size = 20, filled = false } = options;
  const definition = FLUENT_ICON_DEFS[resolveIconName(name)];
  if (!definition) return '';
  return buildFluentSvg(definition, size, filled);
}

export function fluentIconByState(name, options = {}) {
  const { size = 20, active = false, emphasize = false } = options;
  return fluentIcon(name, { size, filled: active || emphasize });
}

export function fluentToneIcon(tone, size = 20) {
  const map = { success: 'success', warning: 'warning', error: 'error', info: 'info' };
  return fluentIcon(map[tone] || 'info', { size, filled: true });
}

